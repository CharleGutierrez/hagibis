    /// Continuous Compilation Monitoring: executes `cargo check` and intercepts diagnostics
    pub fn check_compilation(&self, target_crate: Option<&str>) -> Result<Option<HealingIncidentReport>> {
        self.total_inspected_runs.fetch_add(1, Ordering::SeqCst);

        let mut cmd = Command::new("cargo");
        cmd.arg("check");
        cmd.arg("--message-format=json");
        if let Some(c) = target_crate {
            cmd.args(&["-p", c]);
        }
        cmd.current_dir(&self.workspace_root);

        let output = cmd.output().map_err(|e| {
            HgbError::Execution(format!("Failed to invoke cargo check: {}", e))
        })?;

        if output.status.success() {
            return Ok(None);
        }

        let stderr = String::from_utf8_lossy(&output.stderr).to_string();
        let stdout = String::from_utf8_lossy(&output.stdout).to_string();
        let exit_code = output.status.code().unwrap_or(-1);

        let report = self.intercept_compilation_failure(&stderr, &stdout, exit_code)?;
        self.store.record_incident(&report)?;
        Ok(Some(report))
    }

    /// Continuous Test Suite Monitoring: executes `cargo test` and captures assertion failures / panics
    pub fn check_tests(&self, test_filter: Option<&str>) -> Result<Option<HealingIncidentReport>> {
        self.total_inspected_runs.fetch_add(1, Ordering::SeqCst);

        let mut cmd = Command::new("cargo");
        cmd.arg("test");
        if let Some(f) = test_filter {
            cmd.arg(f);
        }
        cmd.args(&["--", "--nocapture"]);
        cmd.current_dir(&self.workspace_root);

        let output = cmd.output().map_err(|e| {
            HgbError::Execution(format!("Failed to invoke cargo test: {}", e))
        })?;

        if output.status.success() {
            return Ok(None);
        }

        let stderr = String::from_utf8_lossy(&output.stderr).to_string();
        let stdout = String::from_utf8_lossy(&output.stdout).to_string();
        let exit_code = output.status.code().unwrap_or(-1);

        let report = self.intercept_test_failure(&stderr, &stdout, exit_code)?;
        self.store.record_incident(&report)?;
        Ok(Some(report))
    }

    /// Continuous Benchmark Regression Monitoring: compares latency against baseline (>5% regression SLA)
    pub fn check_benchmarks(
        &self,
        benchmark_name: Option<&str>,
        regression_threshold_pct: f64,
    ) -> Result<Option<HealingIncidentReport>> {
        self.total_inspected_runs.fetch_add(1, Ordering::SeqCst);

        let bench_target = benchmark_name.unwrap_or("pgo_representative_workload");

        // Run benchmark runner or microbenchmark
        let start = Instant::now();
        let mut cmd = Command::new("cargo");
        cmd.args(&["test", "--benches", "--", bench_target]);
        cmd.current_dir(&self.workspace_root);

        let output = cmd.output().map_err(|e| {
            HgbError::Execution(format!("Failed to invoke benchmark suite: {}", e))
        })?;

        let observed_latency_us = start.elapsed().as_micros() as f64;

        // Check against recorded baseline in SQLite
        if let Some(baseline_latency_us) = self.store.get_benchmark_baseline(bench_target)? {
            let regression_pct = ((observed_latency_us - baseline_latency_us) / baseline_latency_us) * 100.0;
            if regression_pct > regression_threshold_pct {
                let report = self.intercept_benchmark_regression(
                    bench_target,
                    baseline_latency_us,
                    observed_latency_us,
                )?;
                self.store.record_incident(&report)?;
                return Ok(Some(report));
            }
        } else {
            // Register baseline latency
            self.store.set_benchmark_baseline(bench_target, observed_latency_us)?;
        }

        if !output.status.success() {
            let stderr = String::from_utf8_lossy(&output.stderr).to_string();
            let stdout = String::from_utf8_lossy(&output.stdout).to_string();
            let exit_code = output.status.code().unwrap_or(-1);
            let report = self.intercept_test_failure(&stderr, &stdout, exit_code)?;
            self.store.record_incident(&report)?;
            return Ok(Some(report));
        }

        Ok(None)
    }

