/// Generate standard unified diff preview between original and patched contents
pub fn generate_unified_diff(file_path: &str, original: &str, patched: &str) -> String {
    let mut out = format!("--- a/{}\n+++ b/{}\n", file_path, file_path);
    let orig_lines: Vec<&str> = original.lines().collect();
    let patch_lines: Vec<&str> = patched.lines().collect();

    let mut i = 0;
    let mut j = 0;

    while i < orig_lines.len() || j < patch_lines.len() {
        if i < orig_lines.len() && j < patch_lines.len() && orig_lines[i] == patch_lines[j] {
            out.push_str(&format!(" {}\n", orig_lines[i]));
            i += 1;
            j += 1;
        } else {
            // Collect deletion chunk
            let start_i = i;
            while i < orig_lines.len() && (j >= patch_lines.len() || !patch_lines[j..].contains(&orig_lines[i])) {
                out.push_str(&format!("-{}\n", orig_lines[i]));
                i += 1;
                if i - start_i > 20 {
                    break;
                }
            }
            // Collect addition chunk
            let start_j = j;
            while j < patch_lines.len() && (i >= orig_lines.len() || !orig_lines[i..].contains(&patch_lines[j])) {
                out.push_str(&format!("+{}\n", patch_lines[j]));
                j += 1;
                if j - start_j > 20 {
                    break;
                }
            }
            if i == start_i && j == start_j {
                if i < orig_lines.len() {
                    out.push_str(&format!("-{}\n", orig_lines[i]));
                    i += 1;
                }
                if j < patch_lines.len() {
                    out.push_str(&format!("+{}\n", patch_lines[j]));
                    j += 1;
                }
            }
        }
    }

    out
}

