//! # Pillar 4: Native Fully Autonomous Self-Healing Daemon Engine
//!
//! Native Rust implementation codifying Masterclass Chapter 8 (`docs/masterclass/ch8_autonomous_loops.py`)
//! into a resident, zero-risk self-healing daemon engine (`NativeSelfHealingDaemon`).
//!
//! ## Core Architectural Pipeline:
//! 1. **Continuous Diagnostics Monitoring**:
//!    - **Compilations**: Captures stderr and JSON compiler diagnostics from `cargo check` / `cargo build`
//!      (Rust error codes E0308, E0425, E0433, E0596, etc.).
//!    - **Test Suites**: Monitors test suite runs (`cargo test`), capturing failing assertions (`assert_eq!`),
//!      panics, and line-level stack traces.
//!    - **Benchmark Regressions**: Monitors latency metrics (`hgb-core/benches`, microbenchmarks, Criterion)
//!      and automatically identifies regressions with >5% latency degradation against recorded baselines.
//! 2. **Automated Closed-Loop Self-Healing Pipeline**:
//!    - **Intercept Issue**: Builds a structured `HealingIncidentReport` (incident_id, kind, error_context, affected_files).
//!    - **Draft Candidate Patch**: Queries local LLM agent (via Ollama API `/api/generate`) or applies deterministic
//!      AST repair rules to synthesize a minimal surgical candidate patch (`CandidatePatch`).
//!    - **Sandboxed Speculative Verification**: Prepares an isolated RAM sandbox in `/dev/shm` (RAM CoW overlay)
//!      so the main working tree remains unperturbed during speculative testing.
//!    - **First-Green Assessment**: Verifies patch inside `/dev/shm` (exit code 0, 0 failures, benchmarks restored).
//!      If verification fails, feeds compiler errors back into LLM refinement prompt for up to `max_retries` (default 3).
//!    - **Atomic Workspace Application & Cryptographic Consensus**: On verified First-Green state, atomically applies
//!      patch to workspace disk and generates an immutable `AutonomousConsensusCertificate` with BLAKE3 cryptographic
//!      hashes of original code, patch diff, and verification logs, persisted to `.hgb/self_healing_log.db`.

