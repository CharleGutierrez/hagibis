    #[test]
    fn test_diagnostic_incident_capture_from_compilation_error() {
        let (ws, store) = create_test_env();
        let daemon = NativeSelfHealingDaemon::with_store(&ws, store).unwrap();

        let mock_stderr = r#"
error[E0308]: mismatched types
  --> src/network.rs:42:15
   |
42 |     let buf = "hello";
   |               ^^^^^^^ expected `String`, found `&str`
   |
   = note: consider using `.to_string()`
"#;

        let report = daemon
            .intercept_compilation_failure(mock_stderr, "", 1)
            .expect("intercept failure");

        assert_eq!(report.exit_code, 1);
        assert!(!report.resolved);
        assert!(report.affected_files.contains(&"src/network.rs".to_string()));

        match &report.kind {
            IncidentKind::CompilationError { compiler, error_codes, primary_location } => {
                assert_eq!(compiler, "rustc");
                assert!(error_codes.contains(&"E0308".to_string()));
                assert!(primary_location.is_some());
                let loc = primary_location.as_ref().unwrap();
                assert_eq!(loc.file, "src/network.rs");
                assert_eq!(loc.line, 42);
                assert_eq!(loc.column, 15);
            }
            _ => panic!("Expected IncidentKind::CompilationError"),
        }

        let _ = fs::remove_dir_all(&ws);
    }

    #[test]
    fn test_candidate_patch_formatting_and_ram_cow_verification() {
        let (ws, store) = create_test_env();
        let daemon = NativeSelfHealingDaemon::with_store(&ws, store).unwrap();

        let target_file = ws.join("src/lib.rs");
        fs::create_dir_all(target_file.parent().unwrap()).unwrap();
        let orig_code = "pub fn add_val() -> String {\n    \"test\"\n}\n";
        fs::write(&target_file, orig_code).unwrap();

        let incident = HealingIncidentReport {
            incident_id: "inc_01".to_string(),
            kind: IncidentKind::CompilationError {
                compiler: "rustc".to_string(),
                error_codes: vec!["E0308".to_string()],
                primary_location: Some(DiagnosticLocation {
                    file: "src/lib.rs".to_string(),
                    line: 2,
                    column: 5,
                    message: "expected `String`, found `&str`".to_string(),
                }),
            },
            error_context: "mismatched types: expected `String`, found `&str`".to_string(),
            affected_files: vec!["src/lib.rs".to_string()],
            raw_stderr: "error[E0308]: mismatched types".to_string(),
            raw_stdout: String::new(),
            exit_code: 1,
            created_at: Utc::now().to_rfc3339(),
            resolved: false,
        };

        let patch = daemon.draft_candidate_patch(&incident, None, 1).unwrap();
        assert_eq!(patch.affected_file, "src/lib.rs");
        assert!(patch.diff_preview.contains("+") && patch.diff_preview.contains("-"));
        assert!(patch.patched_content.contains(".to_string()"));

        // Verify inside RAM CoW sandbox: source workspace must remain pristine!
        let mut sandbox = RamCowOverlaySandbox::new(&ws).unwrap();
        sandbox.apply_patch(&patch.affected_file, &patch.patched_content).unwrap();

        let sandboxed_content = sandbox.read_file(&patch.affected_file).unwrap();
        assert!(sandboxed_content.contains(".to_string()"));

        let real_workspace_content = fs::read_to_string(&target_file).unwrap();
        assert_eq!(
            real_workspace_content, orig_code,
            "Workspace disk must NOT be mutated during speculative RAM CoW testing!"
        );

        sandbox.rollback().unwrap();
        let _ = fs::remove_dir_all(&ws);
    }

    #[test]
    fn test_first_green_verification_consensus_and_blake3_certificate() {
        let (ws, store) = create_test_env();
        let daemon = NativeSelfHealingDaemon::with_store(&ws, Arc::clone(&store)).unwrap();

        let target_file = ws.join("src/lib.rs");
        fs::create_dir_all(target_file.parent().unwrap()).unwrap();
        fs::write(&target_file, "pub fn compute() -> usize { 0 }\n").unwrap();

        let incident = HealingIncidentReport {
            incident_id: "inc_cert_01".to_string(),
            kind: IncidentKind::TestFailure {
                suite_name: "test_suite".to_string(),
                failed_tests: vec!["test_compute".to_string()],
                assertion_failures: vec!["assertion `left == right` failed: (0 vs 1)".to_string()],
                panic_traces: vec!["panicked at src/lib.rs:10".to_string()],
            },
            error_context: "assertion `left == right` failed".to_string(),
            affected_files: vec!["src/lib.rs".to_string()],
            raw_stderr: "FAILED".to_string(),
            raw_stdout: String::new(),
            exit_code: 1,
            created_at: Utc::now().to_rfc3339(),
            resolved: false,
        };

        // Run cycle with custom echo command verifying successful exit code 0
        let cert = daemon
            .run_self_healing_cycle(incident, 3, true, Some(("echo", &["First-Green verification passed!"])))
            .expect("self-healing cycle");

        assert!(cert.consensus_reached);
        assert!(cert.applied_to_workspace);
        assert_eq!(cert.total_iterations, 1);
        assert!(!cert.blake3_hash().is_empty());
        assert!(!cert.certificate_hash.is_empty());

        // Validate BLAKE3 consensus certificate in SQLite store
        let retrieved = store.get_certificate(&cert.certificate_id).unwrap().expect("retrieved cert");
        assert_eq!(retrieved.certificate_id, cert.certificate_id);
        assert_eq!(retrieved.certificate_hash, cert.certificate_hash);
        assert_eq!(retrieved.original_code_blake3, cert.original_code_blake3);

        let _ = fs::remove_dir_all(&ws);
    }

    #[test]
    fn test_retry_escalation_when_candidate_patch_fails() {
        let (ws, store) = create_test_env();
        let daemon = NativeSelfHealingDaemon::with_store(&ws, store).unwrap();

        let incident = HealingIncidentReport {
            incident_id: "inc_retry_01".to_string(),
            kind: IncidentKind::CompilationError {
                compiler: "rustc".to_string(),
                error_codes: vec!["E9999".to_string()],
                primary_location: None,
            },
            error_context: "Fatal unrecoverable compiler failure".to_string(),
            affected_files: vec!["src/main.rs".to_string()],
            raw_stderr: "fatal error".to_string(),
            raw_stdout: String::new(),
            exit_code: 1,
            created_at: Utc::now().to_rfc3339(),
            resolved: false,
        };

        // Custom verification command failing with exit code 1
        let cert = daemon
            .run_self_healing_cycle(incident, 3, true, Some(("false", &[])))
            .expect("cycle to execute");

        // Retries must escalate to max_retries (3) and consensus must remain false
        assert_eq!(cert.total_iterations, 3);
        assert!(!cert.consensus_reached);
        assert!(!cert.applied_to_workspace);
        assert!(cert.summary.contains("exhausted 3 iterations"));

        let _ = fs::remove_dir_all(&ws);
    }
