/// High-performance isolated RAM Copy-on-Write (CoW) sandbox residing in `/dev/shm`.
/// Ensures zero risk or pollution to the physical developer workspace during speculative verification.
pub struct RamCowOverlaySandbox {
    pub sandbox_id: String,
    pub base_dir: PathBuf,
    pub merged_dir: PathBuf,
    pub workspace_root: PathBuf,
    pub tracked_files: Vec<String>,
    use_underlying_overlay: Option<OverlaySandbox>,
}

impl RamCowOverlaySandbox {
    /// Instantiate a new RAM CoW sandbox in `/dev/shm` (or fallback tempdir)
    pub fn new(workspace_root: impl AsRef<Path>) -> Result<Self> {
        let ws = workspace_root.as_ref().canonicalize()
            .unwrap_or_else(|_| workspace_root.as_ref().to_path_buf());
        let session_id = uuid::Uuid::new_v4().to_string();
        let sandbox_id = format!("hgb_ram_cow_{}", session_id);

        let shm_root = if Path::new("/dev/shm").is_dir() {
            PathBuf::from("/dev/shm")
        } else {
            std::env::temp_dir()
        };

        let base_dir = shm_root.join(&sandbox_id);
        let merged_dir = base_dir.join("merged");
        fs::create_dir_all(&merged_dir)
            .map_err(|e| HgbError::Storage(format!("Failed to create RAM CoW sandbox dir: {}", e)))?;

        // Attempt kernel OverlaySandbox if applicable, otherwise userspace RAM mirror
        let use_underlying_overlay = OverlaySandbox::new(&ws).ok();

        Ok(Self {
            sandbox_id,
            base_dir,
            merged_dir,
            workspace_root: ws,
            tracked_files: Vec::new(),
            use_underlying_overlay,
        })
    }

    /// Write candidate patched content into the RAM sandbox without touching workspace disk
    pub fn apply_patch(&mut self, rel_path: &str, content: &str) -> Result<()> {
        let rel = Path::new(rel_path);
        let clean_rel = if rel.is_absolute() {
            rel.strip_prefix(&self.workspace_root).unwrap_or(rel)
        } else {
            rel
        };

        let target_in_sandbox = self.merged_dir.join(clean_rel);
        if let Some(parent) = target_in_sandbox.parent() {
            fs::create_dir_all(parent)?;
        }

        fs::write(&target_in_sandbox, content.as_bytes())?;
        self.tracked_files.push(clean_rel.to_string_lossy().to_string());

        if let Some(ref mut overlay) = self.use_underlying_overlay {
            let _ = overlay.write_file(clean_rel, content.as_bytes());
        }

        Ok(())
    }

    /// Read file content from the RAM sandbox
    pub fn read_file(&self, rel_path: &str) -> Result<String> {
        let rel = Path::new(rel_path);
        let clean_rel = if rel.is_absolute() {
            rel.strip_prefix(&self.workspace_root).unwrap_or(rel)
        } else {
            rel
        };

        let target_in_sandbox = self.merged_dir.join(clean_rel);
        if target_in_sandbox.exists() {
            return fs::read_to_string(&target_in_sandbox)
                .map_err(|e| HgbError::Storage(e.to_string()));
        }

        if let Some(ref overlay) = self.use_underlying_overlay {
            if let Ok(bytes) = overlay.read_file(clean_rel) {
                if let Ok(s) = String::from_utf8(bytes) {
                    return Ok(s);
                }
            }
        }

        // Fallback to workspace original
        let ws_file = self.workspace_root.join(clean_rel);
        fs::read_to_string(ws_file).map_err(|e| HgbError::Storage(e.to_string()))
    }

    /// Execute verification command inside the isolated RAM CoW sandbox environment
    pub fn execute_command(&self, cmd: &str, args: &[&str]) -> Result<VerificationResult> {
        let start = Instant::now();

        // If underlying OverlaySandbox is active, route through it
        if let Some(ref overlay) = self.use_underlying_overlay {
            let report = overlay.execute_command(cmd, args)?;
            return Ok(VerificationResult {
                passed: report.success,
                command: report.command,
                exit_code: report.exit_code,
                stdout: report.stdout,
                stderr: report.stderr,
                duration_ms: report.duration_ms,
                remaining_errors: if report.success { 0 } else { 1 },
                benchmark_restored: report.success,
                observed_latency_us: None,
            });
        }

        // Direct isolated invocation in merged_dir
        let mut command = Command::new(cmd);
        command.args(args);
        command.current_dir(&self.merged_dir);

        // Sanitize environment
        command.env("HOME", self.base_dir.join("home"));
        command.env("TMPDIR", self.base_dir.join("tmp"));
        if let Ok(path) = std::env::var("PATH") {
            command.env("PATH", path);
        }
        if let Ok(cargo_home) = std::env::var("CARGO_HOME") {
            command.env("CARGO_HOME", cargo_home);
        }
        if let Ok(rustup_home) = std::env::var("RUSTUP_HOME") {
            command.env("RUSTUP_HOME", rustup_home);
        }

        let output = command.output().map_err(|e| {
            HgbError::Execution(format!("Failed to execute '{}' in RAM CoW sandbox: {}", cmd, e))
        })?;

        let duration_ms = start.elapsed().as_millis() as u64;
        let exit_code = output.status.code().unwrap_or(-1);
        let stdout = String::from_utf8_lossy(&output.stdout).to_string();
        let stderr = String::from_utf8_lossy(&output.stderr).to_string();
        let passed = output.status.success();

        Ok(VerificationResult {
            passed,
            command: format!("{} {}", cmd, args.join(" ")),
            exit_code,
            stdout,
            stderr,
            duration_ms,
            remaining_errors: if passed { 0 } else { 1 },
            benchmark_restored: passed,
            observed_latency_us: None,
        })
    }

    /// Atomically commit verified files from RAM CoW sandbox back to workspace disk
    pub fn commit_to_workspace(&self) -> Result<usize> {
        let mut files_committed = 0;
        for rel_file in &self.tracked_files {
            let src = self.merged_dir.join(rel_file);
            let dst = self.workspace_root.join(rel_file);

            if src.exists() {
                if let Some(parent) = dst.parent() {
                    fs::create_dir_all(parent)?;
                }
                // Atomic replace using temp file in target directory
                let tmp = dst.with_extension(format!("hgb_commit_{}.tmp", uuid::Uuid::new_v4().simple()));
                fs::copy(&src, &tmp)?;
                fs::rename(&tmp, &dst)?;
                files_committed += 1;
            }
        }
        Ok(files_committed)
    }

    /// Discard volatile RAM CoW sandbox layers
    pub fn rollback(self) -> Result<()> {
        let _ = fs::remove_dir_all(&self.base_dir);
        Ok(())
    }
}

impl Drop for RamCowOverlaySandbox {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.base_dir);
    }
}

