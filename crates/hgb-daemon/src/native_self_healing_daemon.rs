    /// Intercept compilation failure and extract structured diagnostics
    pub fn intercept_compilation_failure(
        &self,
        stderr: &str,
        stdout: &str,
        exit_code: i32,
    ) -> Result<HealingIncidentReport> {
        let (error_codes, locations, summary) = Self::parse_compilation_diagnostics(stderr, stdout);

        let mut affected_files: Vec<String> = locations.iter().map(|loc| loc.file.clone()).collect();
        affected_files.sort();
        affected_files.dedup();

        let primary_location = locations.first().cloned();

        let kind = IncidentKind::CompilationError {
            compiler: "rustc".to_string(),
            error_codes,
            primary_location,
        };

        Ok(HealingIncidentReport {
            incident_id: uuid::Uuid::new_v4().to_string(),
            kind,
            error_context: summary,
            affected_files,
            raw_stderr: stderr.to_string(),
            raw_stdout: stdout.to_string(),
            exit_code,
            created_at: Utc::now().to_rfc3339(),
            resolved: false,
        })
    }

    /// Intercept test failure and extract failed test names and assertions
    pub fn intercept_test_failure(
        &self,
        stderr: &str,
        stdout: &str,
        exit_code: i32,
    ) -> Result<HealingIncidentReport> {
        let mut failed_tests = Vec::new();
        let mut assertion_failures = Vec::new();
        let mut panic_traces = Vec::new();
        let mut affected_files = Vec::new();

        for line in stdout.lines().chain(stderr.lines()) {
            let trimmed = line.trim();
            if trimmed.starts_with("test ") && trimmed.ends_with("... FAILED") {
                let name = trimmed["test ".len()..trimmed.len() - "... FAILED".len()].trim();
                failed_tests.push(name.to_string());
            }
            if let Some(pos) = trimmed.find("panicked at '") {
                let after = &trimmed[pos + "panicked at '".len()..];
                if let Some(end_quote) = after.find('\'') {
                    let msg = &after[..end_quote];
                    panic_traces.push(format!("panicked at '{}'", msg));
                    let rest = after[end_quote + 1..].trim();
                    let file_part = rest.trim_start_matches(',').trim();
                    if let Some(col_pos) = file_part.find(':') {
                        affected_files.push(file_part[..col_pos].to_string());
                    }
                }
            }
            if trimmed.contains("assertion") && trimmed.contains("failed") {
                assertion_failures.push(trimmed.to_string());
            }
        }

        affected_files.sort();
        affected_files.dedup();

        let summary = format!(
            "Test suite failed with {} failing test(s): {}. Assertions: {}",
            failed_tests.len(),
            failed_tests.join(", "),
            assertion_failures.join("; ")
        );

        let kind = IncidentKind::TestFailure {
            suite_name: "cargo test".to_string(),
            failed_tests,
            assertion_failures,
            panic_traces,
        };

        Ok(HealingIncidentReport {
            incident_id: uuid::Uuid::new_v4().to_string(),
            kind,
            error_context: summary,
            affected_files,
            raw_stderr: stderr.to_string(),
            raw_stdout: stdout.to_string(),
            exit_code,
            created_at: Utc::now().to_rfc3339(),
            resolved: false,
        })
    }

