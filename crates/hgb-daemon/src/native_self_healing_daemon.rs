/// Diagnostic code location identifying the primary line and column of an error
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct DiagnosticLocation {
    pub file: String,
    pub line: usize,
    pub column: usize,
    pub message: String,
}

/// Classification and telemetry payload of an intercepted issue
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum IncidentKind {
    /// Compilation error from `cargo check` / `cargo build`
    CompilationError {
        compiler: String,
        error_codes: Vec<String>,
        primary_location: Option<DiagnosticLocation>,
    },
    /// Test suite failure from `cargo test`
    TestFailure {
        suite_name: String,
        failed_tests: Vec<String>,
        assertion_failures: Vec<String>,
        panic_traces: Vec<String>,
    },
    /// Benchmark latency regression exceeding acceptable threshold (>5%)
    BenchmarkRegression {
        benchmark_name: String,
        baseline_latency_us: f64,
        observed_latency_us: f64,
        regression_pct: f64,
        percentile: String,
    },
}

impl IncidentKind {
    pub fn label(&self) -> &'static str {
        match self {
            Self::CompilationError { .. } => "CompilationError",
            Self::TestFailure { .. } => "TestFailure",
            Self::BenchmarkRegression { .. } => "BenchmarkRegression",
        }
    }
}

