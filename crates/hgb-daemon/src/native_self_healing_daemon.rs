    /// Parse compiler stderr and stdout for error codes, lines, and messages
    pub fn parse_compilation_diagnostics(
        stderr: &str,
        stdout: &str,
    ) -> (Vec<String>, Vec<DiagnosticLocation>, String) {
        let mut error_codes = Vec::new();
        let mut locations = Vec::new();
        let mut summaries = Vec::new();

        // 1. Parse JSON compiler messages
        for line in stdout.lines().chain(stderr.lines()) {
            if line.starts_with('{') && line.contains("\"reason\":\"compiler-message\"") {
                if let Ok(val) = serde_json::from_str::<serde_json::Value>(line) {
                    if let Some(msg) = val.get("message") {
                        if let Some(code_obj) = msg.get("code") {
                            if let Some(code) = code_obj.get("code").and_then(|c| c.as_str()) {
                                error_codes.push(code.to_string());
                            }
                        }
                        if let Some(rendered) = msg.get("rendered").and_then(|r| r.as_str()) {
                            summaries.push(rendered.to_string());
                        }
                        if let Some(spans) = msg.get("spans").and_then(|s| s.as_array()) {
                            for span in spans {
                                if let (Some(f), Some(l), Some(c)) = (
                                    span.get("file_name").and_then(|v| v.as_str()),
                                    span.get("line_start").and_then(|v| v.as_u64()),
                                    span.get("column_start").and_then(|v| v.as_u64()),
                                ) {
                                    locations.push(DiagnosticLocation {
                                        file: f.to_string(),
                                        line: l as usize,
                                        column: c as usize,
                                        message: msg.get("message").and_then(|m| m.as_str()).unwrap_or("").to_string(),
                                    });
                                }
                            }
                        }
                    }
                }
            }
        }

        // 2. Parse human-readable compiler stderr fallback
        for line in stderr.lines() {
            let trimmed = line.trim();
            if let Some(err_idx) = trimmed.find("error[") {
                if let Some(end_bracket) = trimmed[err_idx..].find(']') {
                    let code = &trimmed[err_idx + 6..err_idx + end_bracket];
                    if code.starts_with('E') && code[1..].chars().all(|c| c.is_ascii_digit()) {
                        error_codes.push(code.to_string());
                        let rest = trimmed[err_idx + end_bracket + 1..].trim_start_matches(':').trim();
                        if !rest.is_empty() {
                            summaries.push(rest.to_string());
                        }
                    }
                }
            } else if trimmed.starts_with("-->") {
                let parts: Vec<&str> = trimmed[3..].trim().split(':').collect();
                if parts.len() >= 3 {
                    locations.push(DiagnosticLocation {
                        file: parts[0].to_string(),
                        line: parts[1].parse().unwrap_or(1),
                        column: parts[2].parse().unwrap_or(1),
                        message: "compiler diagnostic location".to_string(),
                    });
                }
            }
        }

        error_codes.sort();
        error_codes.dedup();

        let final_summary = if !summaries.is_empty() {
            summaries.join("; ")
        } else if !stderr.trim().is_empty() {
            stderr.lines().take(5).collect::<Vec<_>>().join(" ")
        } else {
            "Unknown compilation diagnostic failure".to_string()
        };

        (error_codes, locations, final_summary)
    }

