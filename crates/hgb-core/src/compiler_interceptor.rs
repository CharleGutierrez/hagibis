    #[test]
    fn test_closed_loop_self_healing_python() {
        let tmp = std::env::temp_dir().join(format!("hgb_py_heal_{}", std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_millis()));
        let _ = std::fs::create_dir_all(&tmp);

        let broken_py = "def hello()\n    print('Hello world!')\n";
        let target_file = Path::new("main.py");

        let report = CompilerInterceptor::heal_and_verify(
            &tmp,
            target_file,
            broken_py,
            Some("python3 -m py_compile main.py"),
            3,
        ).expect("heal execution");

        assert!(report.success);
        assert_eq!(report.final_errors, 0);
        assert!(report.committed_to_disk);
        assert!(tmp.join("main.py").exists());
        let on_disk = std::fs::read_to_string(tmp.join("main.py")).unwrap();
        assert!(on_disk.contains("def hello():"));

        let _ = std::fs::remove_dir_all(&tmp);
    }
