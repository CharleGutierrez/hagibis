//! # Autonomous "Self-Healing" Vibe Loops (`hgb-nextgen`)
//!
//! Native Rust implementation porting Masterclass Chapter 8 (`docs/masterclass/ch8_autonomous_loops.py`).
//!
//! ## Architectural Pipeline:
//! 1. **Execution**: Executes `cargo test` or build check on workspace or specified target crate.
//! 2. **Interception**: Intercepts compiler errors (`error[E...]`), runtime panics (`thread '...' panicked`),
//!    assertion failures, and test failure stacks via regex and stderr parsing.
//! 3. **LLM Synthesis**: Prompts local Ollama instance (`http://127.0.0.1:11434` with `dynabook-coder:latest`
//!    or `qwen2.5-coder:1.5b`) with structured error diagnostics, source context, and AST scope to rewrite
//!    code or synthesize unified diff patches. Includes deterministic rule-based heuristic fallback if offline.
//! 4. **RAM CoW Sandbox Isolation**: Evaluates candidate fixes inside an isolated RAM Copy-on-Write sandbox
//!    (`OverlaySandbox` in `/dev/shm`) or microVM jail without touching or dirtying the real git tree.
//! 5. **Sandbox Verification**: Re-runs `cargo test` inside the ephemeral sandbox merged view.
//! 6. **First-Green Commit & BLAKE3 Receipt**: Upon achieving First-Green verification, atomically commits
//!    verified diffs to the workspace or mints a cryptographically signed BLAKE3 `VerifiedPatchReceipt`
//!    and records DPO distillation training pairs in `.hgb/distillation/`.

